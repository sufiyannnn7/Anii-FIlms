-- Alter brand_name to be optional (null)
ALTER TABLE public.site_settings ALTER COLUMN brand_name DROP NOT NULL;

-- Create categories table
CREATE TABLE IF NOT EXISTS public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  section TEXT NOT NULL, -- 'Filmmaking' or 'Marketing'
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable RLS
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;

-- Allow public read access (SELECT)
DROP POLICY IF EXISTS "Allow public SELECT on categories" ON public.categories;
CREATE POLICY "Allow public SELECT on categories" 
ON public.categories FOR SELECT 
TO public 
USING (true);

-- Allow authenticated admins write access (ALL)
DROP POLICY IF EXISTS "Allow authenticated ALL on categories" ON public.categories;
CREATE POLICY "Allow authenticated ALL on categories" 
ON public.categories FOR ALL 
TO authenticated 
USING (true)
WITH CHECK (true);

